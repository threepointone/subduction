#!/usr/bin/env node
// Bundle a self-contained, browser-ready @automerge/automerge into
// ./site/demo/automerge.js so the live demo imports it from the SAME ORIGIN
// (no runtime CDN dependency).
//
// We bundle the package's `fullfat_next_base64` entrypoint, which embeds the
// wasm as base64 and calls `initSync` at module load — so a bare
// `import * as A from "./automerge.js"` yields a fully-initialized Automerge
// (the "next" API: init/change/getChanges/applyChanges/decodeChange/updateText/…)
// with no separate .wasm fetch or explicit init step. esbuild inlines the whole
// graph (including the base64 blob) into one file.

import { build } from "esbuild";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
const entry = `${root}/node_modules/@automerge/automerge/dist/mjs/entrypoints/fullfat_next_base64.js`;
const outfile = `${root}/site/demo/automerge.js`;

const result = await build({
  entryPoints: [entry],
  outfile,
  bundle: true,
  format: "esm",
  platform: "browser",
  target: "es2022",
  legalComments: "none",
  banner: { js: "// Generated by scripts/vendor-automerge.mjs — do not edit.\n// Self-hosted @automerge/automerge (next API, wasm embedded, same-origin)." },
  metafile: true,
});

const bytes = Object.values(result.metafile.outputs).reduce((n, o) => n + o.bytes, 0);
console.log(`bundled @automerge/automerge -> site/demo/automerge.js (${(bytes / 1e6).toFixed(2)} MB)`);
